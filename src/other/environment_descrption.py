def get_event_envDes_llm(text, event_des):
    """
    Extracts the hazard-formative environment description for a given disaster event
    from the provided text using an LLM.
    """
    sys_prompt = """
    你是一位地理灾害分析专家。给定一段【来源文本】和一个已提取的【灾害事件描述】，请从文本中分析并总结出导致该事件发生的“孕灾环境”描述。
    【定义】
    孕灾环境（Hazard-formative Environment）是灾害发生的背景条件。
    【提取要求】
    1. 描述精炼完整：字数控制在10个字以内，如“地势低洼”、“高山边坡”、“强降雨期”、“土质疏松”。
    2. 维度涵盖：地形地貌、气象水文、地质条件、人类活动等。
    3. 严禁冗长：不要使用“该地区地势非常...”等完整句子，直接输出属性词。
    """

    user_prompt = f"""
    【原始文本】: {text}
    【灾害事件】: {event_des}

    请根据原始文本，总结该事件发生的孕灾环境特征：
    """

    from pydantic import BaseModel, Field
    from typing import List

    class EnvDesInfo(BaseModel):
        env_des: List[str] = Field(description="孕灾环境描述集合")

    agent = create_agent(llm, system_prompt=sys_prompt, response_format=EnvDesInfo)
    output = agent.invoke(
        {"messages": [
            {"role": "user", "content": user_prompt}
        ]}
    )
    return output["structured_response"]


def get_save_event_envDes(event_node):
    """
    Retrieves the original text for an event node, uses the LLM to extract
    the environment description, and saves it to the Neo4j database.
    """
    event_des = event_node.event_description
    text_nodes = event_node.origin.all()
    text_contents = [text_node.text_content for text_node in text_nodes]
    origin_text = "".join(text_contents)

    res_info = get_event_envDes_llm(origin_text, event_des)
    event_envDes = res_info.env_des
    event_envDes_str = "-".join(event_envDes)
    envDes_node = EnvironmentDescription.nodes.first_or_none(description=event_envDes_str)
    if not envDes_node:
        envDes_node = EnvironmentDescription(description=event_envDes_str)
        envDes_node.save()
    if not event_node.envDes_argument.is_connected(envDes_node):
        event_node.envDes_argument.connect(envDes_node)
    print(f"{event_des}\n{origin_text}\n------------------------------{event_envDes}-------------------------------")


class Constraint(BaseModel):
    factor: str = Field(description="关键因子：slope 或 abs_elevation")
    operator: str = Field(description="操作符：> | < | >= | <= | between")
    value: Union[float, List[float]] = Field(description="数值或数值范围")
    unit: str = Field(description="单位：° 或 m")


class SpatialRule(BaseModel):
    target_object: str = Field(description="限定对象类型：Terrain, Slope_Body, Drainage_Area, Water_Body, Urban_Area")
    logic: str = Field(description="逻辑运算符：AND 或 OR")
    constraints: List[Constraint]


class RuleOutput(BaseModel):
    inference_logic: dict = Field(description="包含描述分析和科学依据的推理过程")
    spatial_rule: SpatialRule


def get_env_rule_chain(event: str, env_description: str, addition_info: dict):
    """
    Converts qualitative environment descriptions into quantitative spatial rules
    (like elevation and slope constraints) using a Chain-of-Thought LLM approach.
    """
    system_prompt = """
        你是一位资深的自然地理学专家与防灾减灾工程逻辑分析师。你的任务是将事理图谱（OELG）中关于灾害孕灾环境的“模糊定性描述”转化为基于 高程 (Elevation) 和 坡度 (Slope) 的定量判别逻辑。

        【限定范围约束】
        - 对象类型 (Object Types): Terrain, Slope_Body, Drainage_Area, Water_Body, Urban_Area
        - 关键因子 (Key Factors): slope (度 °), abs_elevation (米 m)

        【思维链 (CoT) 推理步骤】
        R1 - 对象解析：提取受影响的核心地理对象类型。
        R2 - 语义映射：将定性词汇映射到高程或坡度（如“陡峭”->坡度；“低洼”->高程）。
        R3 - 数值量化：基于地理学常识设定阈值（如：极陡坡 > 35°，陡坡 25-35°）。
        R4 - 规则形式化：构建逻辑表达式。

        {format_instructions}
    """

    avg_elevation = addition_info.get('elevation', '')
    agent = create_agent(llm, system_prompt=system_prompt, response_format=RuleOutput)
    output = agent.invoke(
        {"messages": [{"role": "user",
                       "content": f"当前灾害事件为‘{event}’，其孕灾环境描述为：{env_description}’，该地区平均高程为{avg_elevation}米"}]}
    )
    return output["structured_response"]


def evaluate_feature_against_rule(feature, rule_data) -> bool:
    """
    Evaluates whether a single geographic feature satisfies the spatial rules
    generated by the LLM.
    """
    if not rule_data or 'spatial_rule' not in rule_data:
        return True

    spatial_rule = rule_data['spatial_rule']
    constraints = spatial_rule.get('constraints', [])
    logic = spatial_rule.get('logic', 'AND').upper()

    props = feature.get('properties', {})
    val_map = {
        'abs_elevation': props.get('avg_elevation', props.get('elevation', 0)),
        'rel_elevation': props.get('avg_elevation', 0),
        'slope': props.get('avg_slope', 0)
    }

    results = []

    for const in constraints:
        factor = const.get('factor')
        operator = const.get('operator')
        threshold = const.get('value')

        actual_val = val_map.get(factor, 0)
        if actual_val is None: actual_val = 0

        res = False
        try:
            if operator == '>':
                res = actual_val > float(threshold)
            elif operator == '>=':
                res = actual_val >= float(threshold)
            elif operator == '<':
                res = actual_val < float(threshold)
            elif operator == '<=':
                res = actual_val <= float(threshold)
            elif operator == 'between':
                if isinstance(threshold, list) and len(threshold) >= 2:
                    res = threshold[0] <= actual_val <= threshold[1]
                else:
                    res = True
            elif operator == '==':
                res = actual_val == float(threshold)
        except Exception as e:
            print(f"Error evaluating rule: {e}")
            res = True

        results.append(res)

    if not results:
        return True

    if logic == 'OR':
        return any(results)
    else:
        return all(results)


def generate_env_rule(ori_disaster_des: str):
    """
    Generates environment rules for secondary disasters caused by the specified
    original disaster and connects them in the database.
    """
    ori_disaster = GlobalDisasterEvent.nodes.first_or_none(event_description=ori_disaster_des)
    ori_geo_name = ori_disaster_des.split(',')[0]

    scd_disasters = ori_disaster.cause.all()

    for scd_disaster in scd_disasters:
        scd_disaster_des = scd_disaster.event_description

        scd_geo_list = scd_disaster.geo_argument.all()
        if not scd_geo_list:
            continue
        scd_geo_name = scd_geo_list[0].geo_object_name

        if ori_geo_name == scd_geo_name:
            continue

        rs = ori_disaster.cause.all_relationships(scd_disaster)

        for r in rs:
            pattern = r.cluster_pattern
            ori_merge = MergeDisasterEvent.nodes.first_or_none(event_description=ori_disaster_des,
                                                               cluster_pattern=pattern)
            scd_merge = MergeDisasterEvent.nodes.first_or_none(event_description=scd_disaster_des,
                                                               cluster_pattern=pattern)

            if ori_merge and scd_merge:
                envDes = ""
                scd_disaster_envDes = scd_merge.envDes_argument.all()
                if len(scd_disaster_envDes) > 0:
                    envDes = scd_disaster_envDes[0].description
                    print(envDes)

                addition_info = {'elevation': 190}

                env_rule = get_env_rule_chain(ori_disaster_des, envDes, addition_info)

                print(env_rule)


def generate_env_rule_to_database():
    """
    Iterates through all MergeDisasterEvent nodes, generates environment rules
    for them, and saves the rules to the database.
    """
    disasters = MergeDisasterEvent.nodes.all()

    for disaster in disasters:
        scd_disaster = disaster.cause.all()
        for scd in scd_disaster:
            print(scd.event_description)
            envDes = ""
            disaster_envDes = scd.envDes_argument.all()
            if len(disaster_envDes) > 0:
                disaster_envDes_node = disaster_envDes[0]
                envDes = disaster_envDes_node.description
                rules = scd.envRule_argument.all()
                print(envDes)

                if len(rules) == 0:
                    addition_info = {'elevation': 120}
                    env_rules = get_env_rule_chain(scd.event_description, envDes, addition_info)
                    if hasattr(env_rules, 'dict'):
                        env_rules = env_rules.dict()
                    elif hasattr(env_rules, 'model_dump'):
                        env_rules = env_rules.model_dump()
                    else:
                        env_rules = env_rules

                    rule_node = EnvironmentRule(rules=env_rules).save()

                    if not disaster.envRule_argument.is_connected(rule_node):
                        disaster.envRule_argument.connect(rule_node)

                    print(env_rules)


